def gtk_handles(tok, keymap):
    """Keys NORMAL mode leaves to GTK: Tab / Shift+Tab move the focus (to
    Deny / Run), and Ctrl chords that aren't ours (Ctrl+C copies a selected
    command)."""
    return tok in ("<Tab>", "<S-Tab>") or (tok.startswith("<C-") and keymap.lookup(tok)[0] is None)


